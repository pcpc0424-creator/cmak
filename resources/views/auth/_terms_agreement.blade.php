<p style="font-weight:700;margin:14px 0 6px;color:#222;">제1장 총칙</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 1 조 (목적)</p>
<p style="margin:2px 0;">1. 본 약관은 한국CM협회(이하 "협회")가 제공하는 인터넷 서비스(이하 "서비스")의</p>
<p style="margin:2px 0;">이용조건 및 절차, 사용자와 협회의 권리, 의무, 책임사항과 기타 필요한 사항을 규정함을 목적으로 합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 2 조 (약관의 효력과 변경)</p>
<p style="margin:2px 0;">1. 협회는 귀하가 본 약관 내용에 동의하는 경우, 협회의 서비스 제공 행위 및 귀하의 서비스 사용 행위에 본 약관이 우선적으로</p>
<p style="margin:2px 0;">적용됩니다.</p>
<p style="margin:2px 0;">2. 협회는 본 약관을 변경할 경우 변경된 약관을 협회 홈페이지 또는 E-MAIL을 통해 회원에게 공지하며, 공지와 동시에</p>
<p style="margin:2px 0;">그 효력이 발생됩니다. 만약, 사용자가 변경된 약관에 동의하지 않는 경우 회원등록을 취소(회원탈퇴)할 수 있으며, 계속 사용할</p>
<p style="margin:2px 0;">경우에는 약관 변경에 대한 동의로 간주됩니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 3 조 (약관 외 준칙)</p>
<p style="margin:2px 0;">1. 본 약관에 명시되지 않은 사항은 전기통신기본법, 전기통신사업법, 정보통신윤리위원회심의 규정, 정보통신 윤리강령, 프로그램보호법</p>
<p style="margin:2px 0;">및 기타 관련 법령의 규정에 의합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 4 조 (용어의 정의)</p>
<p style="margin:2px 0;">본 약관에서 사용하는 용어의 정의는 다음과 같습니다.</p>
<p style="margin:2px 0;">1. 사용자 : 본 약관에 따라 협회가 제공하는 정보서비스를 받는 자.</p>
<p style="margin:2px 0;">2. 사용자등록 : 협회가 제공하는 신청서 양식에 해당 정보를 기입하고, 본 약관에 동의하여 서비스 이용계약을 완료시키는</p>
<p style="margin:2px 0;">행위.</p>
<p style="margin:2px 0;">3. 서비스회원 : 협회에 개인정보를 제공하여 사용자등록을 한 자로서, 서비스를 이용할 수 있는 자를 다음 각 호와 같이</p>
<p style="margin:2px 0;">구분한다.</p>
<p style="margin:2px 0;">1) 정회원 : 서비스 이용시점을 기준으로 협회정관 제6조에 의한 회원가입을 한 일반회원, 일반회원 소속 임직원, 특별회원</p>
<p style="margin:2px 0;">2) 준회원 : 건설기술관리법 제2조 제5호 및 같은법 시행령 제3조의2의 발주청에 소속된 임직원</p>
<p style="margin:2px 0;">3) 인터넷회원 : 위의 1) 또는 2)에 속하지 않는 개인 혹은 회사, 단체</p>
<p style="margin:2px 0;">4. 사용자ID : 회원식별 및 서비스 이용 등을 위해 사용자등록 신청자가 직접 설정, 입력하는 문자와 숫자로 이뤄진 조합을</p>
<p style="margin:2px 0;">뜻하며 하나의 사용자ID로 협회가 제공하는 서비스를 이용할 수 있습니다.</p>
<p style="margin:2px 0;">5. 비밀번호 : 사용자와 회원ID가 일치하는지를 확인하고 통신상의 자신의 비밀보호를 위하여 사용자 자신이 선정한 문자와</p>
<p style="margin:2px 0;">숫자의 조합.</p>
<p style="margin:2px 0;">6. 사용자 기본정보 : 제3자가 본인의 신원을 확인할 수 있는 개인정보를 의미합니다.</p>
<p style="margin:2px 0;">7. 등록해지 : 회원이 이용계약을 종료시키는 행위.</p>
<p style="font-weight:700;margin:14px 0 6px;color:#222;">제2장 서비스 제공 및 이용</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 5 조 (이용계약의 성립)</p>
<p style="margin:2px 0;">1. 이용계약은 신청자가 온라인으로 협회에서 제공하는 소정의 가입신청 양식에서 요구하는 사항을 기록하여 가입을 완료하는 것으로</p>
<p style="margin:2px 0;">성립됩니다.</p>
<p style="margin:2px 0;">2. 협회는 다음 각 호에 해당하는 이용계약에 대하여는 가입을 취소할 수 있습니다.</p>
<p style="margin:2px 0;">1) 다른 사람의 명의를 사용하여 신청하였을 때</p>
<p style="margin:2px 0;">2) 이용계약 신청서의 내용을 허위로 기재하였거나 신청하였을 때</p>
<p style="margin:2px 0;">3) 다른 사람의 협회 서비스 이용을 방해하거나 그 정보를 도용하는 등의 행위를 하였을 때</p>
<p style="margin:2px 0;">4) 협회를 이용하여 법령과 본 약관이 금지하는 행위를 하는 경우</p>
<p style="margin:2px 0;">5) 기타 협회가 정한 이용신청 요건이 미비되었을 때</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 6 조 (서비스 이용의 범위)</p>
<p style="margin:2px 0;">1. 정회원 및 준회원 : 협회에서 제공되는 모든 서비스를 이용할 수 있다.</p>
<p style="margin:2px 0;">2. 인터넷회원 : 협회가 정한 범위 내의 서비스를 이용할 수 있다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 7 조 (회원정보 사용에 대한 동의)</p>
<p style="margin:2px 0;">1. 회원의 개인정보는 공공기관의 개인정보보호에 관한 법률에 의해 보호됩니다.</p>
<p style="margin:2px 0;">2. 협회의 회원 정보는 다음과 같이 사용, 관리, 보호됩니다.</p>
<p style="margin:2px 0;">1) 개인정보의 사용 : 협회는 서비스 제공과 관련해서 수집된 회원의 신상정보를 본인의 승낙 없이 제3자에게 누설, 배포하지</p>
<p style="margin:2px 0;">않습니다. 단, 전기통신기본법 등 법률의 규정에 의해 국가기 관의 요구가 있는 경우, 범죄에 대한 수사상의 목적이 있거나 정보통신윤리위원회의</p>
<p style="margin:2px 0;">요청이 있는 경우 또는 기타 관계법령에서 정한 절차에 따른 요청이 있는 경우, 귀하가 협회에 제공한 개인정보를 스스로 공개한</p>
<p style="margin:2px 0;">경우에는 그러하지 않습니다.</p>
<p style="margin:2px 0;">2) 개인정보의 관리 : 귀하는 개인정보의 보호 및 관리를 위하여 서비스의 개인정보관리에서 수시로 귀하의 개인정보를 수정/삭제할 수 있습니다.</p>
<p style="margin:2px 0;">3) 개인정보의 보호 : 귀하의 개인정보는 오직 귀하만이 열람/수정/삭제 할 수 있으며, 이는 전적으로 귀하의 ID와 비밀번호에 의해</p>
<p style="margin:2px 0;">관리되고 있습니다. 따라서 타인에게 본인의 ID와 비밀 번호를 알려주어서는 안되며, 작업 종료시에는 반드시 로그아웃 해주시기 바랍니다.</p>
<p style="margin:2px 0;">3. 회원이 본 약관에 따라 이용신청을 하는 것은, 협회가 신청서에 기재된 회원정보를 수집, 이용하는 것에 동의하는 것으로</p>
<p style="margin:2px 0;">간주됩니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 8 조 (사용자의 정보 보안)</p>
<p style="margin:2px 0;">1. 가입 신청자가 협회 서비스 가입 절차를 완료하는 순간부터 귀하는 입력한 정보의 비밀을 유지할 책임이 있으며, 회원의</p>
<p style="margin:2px 0;">ID와 비밀번호를 사용하여 발생하는 모든 결과에 대한 책임은 회원 본인에게 있습니다.</p>
<p style="margin:2px 0;">2. ID와 비밀번호에 관한 모든 관리의 책임은 회원에게 있으며, 회원의 ID나 비밀번호가 부정하게 사용되었다는 사실을 발견한</p>
<p style="margin:2px 0;">경우에는 즉시 협회에 신고 하여야 합니다. 신고를 하지 않음으로 인한 모든 책임은 회원 본인에게 있습니다.</p>
<p style="margin:2px 0;">3. 사용자는 협회 서비스의 사용 종료시 마다 정확히 접속을 종료해야 하며, 정확히 종료하지 아니함으로써 제3자가 귀하에</p>
<p style="margin:2px 0;">관한 정보를 이용하게 되는 등의 결과로 인해 발생하는 손해 및 손실에 대하여 협회는 책임을 부담하지 아니합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 9 조 (서비스의 중지)</p>
<p style="margin:2px 0;">1. 협회는 사용자가 본 약관의 내용에 위배되는 행동을 한 경우, 임의로 서비스 사용을 제한 및 중지할 수 있습니다.</p>
<p style="margin:2px 0;">2. 협회는 양질의 서비스 제공을 위하여 S/W 및 H/W, Network의 이설 및 증설, 유지보수 등을 사유로 일시 서비스를</p>
<p style="margin:2px 0;">중지할 수 있습니다.</p>
<p style="margin:2px 0;">3. 협회 정회원 중에서 협회비 납부의무를 성실히 준수하지 않는 회원에 대하여는 서비스를 중지 또는 제한할 수 있습니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 10 조 (정보서비스 이용책임)</p>
<p style="margin:2px 0;">1. 협회는 귀하가 서비스를 이용하여 기대하는 손익이나 서비스를 통하여 얻은 자료로 인한 손해에 관하여 책임을 지지 않으며,</p>
<p style="margin:2px 0;">회원이 본 서비스에 게재한 정보, 자료, 사실의 신뢰도, 정확성 등 내용에 관하여는 책임을 지지 않습니다.</p>
<p style="margin:2px 0;">2. 협회는 서비스 이용과 관련하여 가입자에게 발생한 손해 중 가입자의 고의, 과실에 의한 손해에 대하여 책임을 부담하지</p>
<p style="margin:2px 0;">아니합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 11 조 (게시물의 저작권)</p>
<p style="margin:2px 0;">1. 귀하가 게시한 게시물의 내용에 대한 권리는 귀하에게 있습니다.</p>
<p style="margin:2px 0;">2. 협회는 게시된 내용을 사전 통지 없이 편집, 이동할 수 있는 권리를 보유하며, 운영원칙에 따라 사전 통지없이 삭제할</p>
<p style="margin:2px 0;">수 있습니다.</p>
<p style="margin:2px 0;">3. 귀하의 게시물이 타인의 저작권을 침해함으로써 발생하는 민, 형사상의 책임은 전적으로 귀하가 부담하여야 합니다.</p>
<p style="font-weight:700;margin:14px 0 6px;color:#222;">제3장 의무 및 책임</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 12 조 (협회의 의무)</p>
<p style="margin:2px 0;">1. 협회는 회원의 개인 신상정보를 본인의 승낙없이 타인에게 누설, 배포하지 않습니다. 다만, 전기통신관련법령 등 관계법령에</p>
<p style="margin:2px 0;">의하여 관계 국가기관 등의 요구가 있는 경우에는 그러하지 아니합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 13 조 (회원의 의무)</p>
<p style="margin:2px 0;">1. 회원 가입시에 요구되는 정보는 정확하게 기입하여야 합니다. 또한 이미 제공된 귀하에 대한 정보에 대한 변경사항이 있을</p>
<p style="margin:2px 0;">경우 정확한 정보가 유지될 수 있도록 갱신하여야 하며, 회원은 자신의 ID 및 비밀번호를 제3자에게 이용하게 해서는 안됩니다.</p>
<p style="margin:2px 0;">2. 협회는 서비스의 회원관리를 위하여 등록된 회원정보를 수정·확인을 요청할 수 있으며 이때 본인의 회원가입 기본정보를 정확하게</p>
<p style="margin:2px 0;">수정·확인해야 하며 본인의 기본정보를 부정확 또는 불성실하게 작성시 ID를 임의로 삭제할 수 있습니다.</p>
<p style="margin:2px 0;">3. 회원은 협회의 사전 승낙 없이 서비스를 이용하여 어떠한 영리행위도 할 수 없습니다.</p>
<p style="font-weight:700;margin:14px 0 6px;color:#222;">제4장 기타사항</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 14 조 (양도금지)</p>
<p style="margin:2px 0;">1. 회원이 서비스의 이용권한, 기타 이용계약 상 지위를 타인에게 양도, 증여할 수 없습니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 15 조 (손해배상)</p>
<p style="margin:2px 0;">1. 협회는 서비스와 관련하여 회원에게 어떠한 손해가 발생하더라도 협회가 고의로 행한 범죄행위를 제외하고 이에 대하여 책임을</p>
<p style="margin:2px 0;">부담하지 아니합니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 16 조 (면책조항)</p>
<p style="margin:2px 0;">1. 협회는 회원이나 제3자에 의해 표출된 의견을 승인하거나 반대하거나 수정하지 않습니다. 또한 협회는 어떠한 경우라도 회원이</p>
<p style="margin:2px 0;">서비스에 담긴 정보에 의존해 얻은 이득이나 입은 손해에 대해 책임이 없습니다.</p>
<p style="margin:2px 0;">2. 협회는 회원간 또는 회원과 제3자간에 서비스를 매개로 하여 물품거래 또는 금전적 거래 등과 관련하여 어떠한 책임도 부담하지</p>
<p style="margin:2px 0;">아니하며, 회원이 서비스의 이용과 관련하여 기대하는 이익에 관하여도 책임을 부담하지 않습니다.</p>
<p style="font-weight:600;margin:10px 0 4px;color:#333;">제 17 조 (재판관할)</p>
<p style="margin:2px 0;">1. 협회와 사용자간에 발생한 서비스 이용에 관한 분쟁에 대하여는 대한민국 법을 적용하며, 본 분쟁으로 인한 소는 협회의</p>
<p style="margin:2px 0;">소재지 관할법원에 제기합니다.</p>
